export const problemById = (id) => PROBLEMS.find((p) => p.id === id) || null;
export const problemsByTopic = (topicId) => PROBLEMS.filter((p) => p.topic === topicId).sort((a, b) => a.order - b.order);
export const topicById = (id) => TOPICS.find((t) => t.id === id) || null;
export const skillById = (id) => SKILLS.find((s) => s.id === id) || null;

/** Exact output of a mission's rule. */
export const evaluateRule = (problem, v) => problem.start + problem.step * (v - problem.n0);
/** Slope m and intercept c of y = m·v + c. */
export const ruleCoefficients = (problem) => ({ m: problem.step, c: problem.start - problem.step * problem.n0 });
